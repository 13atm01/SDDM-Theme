set -e

# Output colors
GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
RESET='\033[0m'

THEME_NAME="Mornye"
THEME_DIR="/usr/share/sddm/themes"
SDDM_CONF_DIR="/etc/sddm.conf.d"
SDDM_CONF_FILE="$SDDM_CONF_DIR/Mornye.conf"

# Get absolute path of script directory
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )"

print_header() {
    echo -e "${CYAN}"
    echo "╔══════════════════════════════════════════════════════╗"
    echo "║         Wuthering Waves | Mornye SDDM Theme          ║"
    echo "║                          by                          ║"
    echo "║                  Andi Trisna Mukti                   ║"
    echo "╚══════════════════════════════════════════════════════╝"
    echo -e "${RESET}"
}

check_root() {
    if [[ $EUID -ne 0 ]]; then
        echo -e "${RED}Error: This script must be run with sudo/root${RESET}"
        echo "Usage: sudo ./install.sh"
        exit 1
    fi
}

check_sddm() {
    if ! command -v sddm &> /dev/null; then
        echo -e "${RED}Error: SDDM is not installed on this system${RESET}"
        exit 1
    fi
    echo -e "${GREEN}✓ SDDM detected${RESET}"
}

backup_existing() {
    if [[ -d "$THEME_DIR/$THEME_NAME" ]]; then
        echo -e "${YELLOW}⚠ Theme $THEME_NAME already exists. Creating backup...${RESET}"
        BACKUP_NAME="${THEME_NAME}_backup_$(date +%Y%m%d_%H%M%S)"
        sudo cp -r "$THEME_DIR/$THEME_NAME" "$THEME_DIR/$BACKUP_NAME"
        echo -e "${GREEN}✓ Backup created: $THEME_DIR/$BACKUP_NAME${RESET}"
    fi
}

install_theme() {
    echo -e "\n${CYAN}📦 Installing theme $THEME_NAME...${RESET}"
    echo -e "Source directory: ${SCRIPT_DIR}"

    # Create destination directory
    sudo mkdir -p "$THEME_DIR/$THEME_NAME"

    # Copy ALL files from script directory to theme directory
    sudo cp -r "$SCRIPT_DIR"/. "$THEME_DIR/$THEME_NAME/"

    # Remove repository files that are not needed by SDDM
    sudo rm -f "$THEME_DIR/$THEME_NAME/install.sh"
    sudo rm -f "$THEME_DIR/$THEME_NAME/uninstall.sh"

    # Set correct permissions
    sudo chmod -R 644 "$THEME_DIR/$THEME_NAME/"
    sudo chmod 755 "$THEME_DIR/$THEME_NAME"

    # Ensure subdirectories are executable
    for dir in "$THEME_DIR/$THEME_NAME"/*/; do
        if [[ -d "$dir" ]]; then
            sudo chmod 755 "$dir"
        fi
    done

    echo -e "${GREEN}✓ Theme files copied to $THEME_DIR/$THEME_NAME${RESET}"
}

configure_sddm() {
    echo -e "\n${CYAN}⚙️  Configuring SDDM...${RESET}"

    sudo mkdir -p "$SDDM_CONF_DIR"

    # Remove conflicting theme configurations
    echo -e "${YELLOW}Removing conflicting theme configurations...${RESET}"
    sudo rm -f "$SDDM_CONF_DIR/default.conf"
    sudo rm -f "$SDDM_CONF_DIR/theme.conf"
    sudo rm -f "$SDDM_CONF_DIR/breeze.conf"
    sudo rm -f "$SDDM_CONF_DIR/maui.conf"

    # Create theme configuration
    sudo tee "$SDDM_CONF_FILE" > /dev/null <<EOF
# Wuthering Waves | Mornye SDDM Theme
# Auto-generated by install.sh

[Theme]
Current=$THEME_NAME
EOF

    echo -e "${GREEN}✓ SDDM configuration created at $SDDM_CONF_FILE${RESET}"

    # Also update /etc/sddm.conf directly (for distros that don't read from .d/)
    if [[ -f /etc/sddm.conf ]]; then
        echo -e "${YELLOW}Updating /etc/sddm.conf as well...${RESET}"
        sudo cp /etc/sddm.conf /etc/sddm.conf.backup.$(date +%Y%m%d)

        if grep -q "^\[Theme\]" /etc/sddm.conf; then
            sudo sed -i "s/^Current=.*/Current=$THEME_NAME/" /etc/sddm.conf
        else
            sudo tee -a /etc/sddm.conf > /dev/null <<EOF

[Theme]
Current=$THEME_NAME
EOF
        fi
        echo -e "${GREEN}✓ /etc/sddm.conf updated${RESET}"
    fi

    # Verify configuration
    echo -e "\n${CYAN}📋 Current SDDM theme configuration:${RESET}"
    if [[ -f "$SDDM_CONF_FILE" ]]; then
        cat "$SDDM_CONF_FILE"
    fi
}

print_success() {
    echo -e "\n${GREEN}╔════════════════════════════════════════════════════╗${RESET}"
    echo -e "${GREEN}║        Wuthering Waves | Mornye SDDM Theme         ║${RESET}"
    echo -e "${GREEN}║            ✅ Successfully Installed ✅            ║${RESET}"
    echo -e "${GREEN}╚════════════════════════════════════════════════════╝${RESET}"

    echo -e "\n${CYAN}🧪 Want to test the theme before restarting?${RESET}"
    echo -e "Run this command in your terminal:"
    echo -e "${YELLOW}sddm-greeter-qt6 --test-mode --theme $THEME_DIR/$THEME_NAME${RESET}"
    echo -e "(Press Ctrl+C to exit the preview)\n"

    echo -e "${CYAN}🔄 Ready to apply the theme?${RESET}"
    echo -e "When you're ready, restart SDDM to see the changes:"
    echo -e "${YELLOW}sudo systemctl restart sddm${RESET}"
    echo -e "${YELLOW}(Make sure to save all your work before restarting!)${RESET}\n"
}

# ===== MAIN =====
print_header
check_root
check_sddm
backup_existing
install_theme
configure_sddm
print_success
